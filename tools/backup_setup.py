"""One-time Linux/Proton setup. Produces a launcher for Steam's launch options."""
import argparse
import hashlib
import json
import os
from pathlib import Path
import shutil
import sys


def setup(mod, save_root):
    if sys.version_info < (3, 9) or os.name != 'posix' or not shutil.which('systemd-run'):
        raise RuntimeError('Proton backups require Python3.9+ and user systemd')
    mod, save_root = Path(mod).resolve(), Path(save_root).resolve()
    if not (mod/'config.lua').is_file() or not (mod/'tools/backup_session.py').is_file():
        raise ValueError('Use the installed Growing Grounds folder')
    if not save_root.is_dir() or save_root.name != 'SaveGames':
        raise ValueError('Select the actual Pal/Saved/SaveGames directory')
    key = hashlib.sha256(str(save_root).encode()).hexdigest()[:12]
    state = save_root.parent/'GrowingGroundsBackupState'
    state.mkdir(parents=True, exist_ok=True, mode=0o700)
    profile = state/'linux-profile.json'
    data = {'session_unit': 'gg-palworld-'+key, 'backup_unit': 'gg-archive-'+key,
            'state': str(state), 'destination': str(save_root.parent/'GrowingGroundsBackups'),
            'mod': str(mod), 'save_root': str(save_root), 'quiet_seconds': 120,
            'version': (mod/'backup-version.txt').read_text().strip()}
    if profile.exists():
        old = json.loads(profile.read_text())
        if any(old.get(k) != data[k] for k in ('save_root', 'destination', 'mod')):
            raise ValueError('Existing backup profile belongs to a different installation')
    temporary = profile.with_suffix('.tmp');temporary.write_text(json.dumps(data, indent=2)+'\n');temporary.replace(profile)
    launcher = state/'gg-launch'
    # Only the private, generated profile path is embedded; game argv is passed unchanged.
    launcher.write_text('''#!/usr/bin/env python3
# Growing Grounds managed session launcher; generated by backup_setup.py.
import json, os, subprocess, sys
from pathlib import Path
profile = Path('''+repr(str(profile))+''')
p = json.loads(profile.read_text())
if len(sys.argv) < 2:
    raise SystemExit('Use this launcher with the original game command, or Steam %command%.')
command = ['systemd-run', '--user', '--quiet', '--collect', '--wait', '--pipe',
           '--unit='+p['session_unit'], '--property=KillSignal=SIGINT', '--property=TimeoutStopSec=90s']
# --setenv=NAME copies the value without exposing it in command arguments.
command += ['--setenv='+key for key in sorted(os.environ)]
command += [sys.executable, str(Path(p['mod'])/'tools/backup_session.py'), 'launch', str(profile), '--']
raise SystemExit(subprocess.call(command+sys.argv[1:]))
''')
    launcher.chmod(0o700)
    return launcher, profile


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--mod', type=Path, default=Path(__file__).resolve().parents[1])
    p.add_argument('--save-root', required=True, type=Path)
    args = p.parse_args()
    launcher, profile = setup(args.mod, args.save_root)
    import shlex
    print('Steam launch options: '+shlex.quote(str(launcher))+' %command%')
    print('Profile: '+str(profile))
    print('Archives: '+str(args.save_root.resolve().parent/'GrowingGroundsBackups'))


if __name__ == '__main__':
    main()
